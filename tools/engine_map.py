#!/usr/bin/env python3
"""Generate `docs/engine-map.md`: what lives where in the one-file engine.

    python3 tools/engine_map.py            # write it
    python3 tools/engine_map.py --check    # exit 1 if it is out of date (used by the test suite)

`engine/humona.py` is deliberately a single file — a hook has roughly 0.2 s to start, and import
cost is the first thing a package split would spend. The honest answer to "3,000 lines in one
file" is therefore a map of it rather than a reorganisation, and a generated map cannot drift from
the code the way a hand-written one does.
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ENGINE = REPO / "engine" / "humona.py"
OUT = REPO / "docs" / "engine-map.md"
SECTION_RE = re.compile(r"^# -{5,} (.+?) -{5,}\s*$")
DEF_RE = re.compile(r"^(?:def|class) (\w+)")
HDR = "<!-- generated by `python3 tools/engine_map.py` — do not edit by hand -->"


def sections(text):
    """(title, first line, last line, [top-level names]) for each `# ----- section -----` block."""
    lines = text.splitlines()
    marks = [(i, SECTION_RE.match(l).group(1)) for i, l in enumerate(lines, 1) if SECTION_RE.match(l)]
    out = []
    for n, (start, title) in enumerate(marks):
        end = marks[n + 1][0] - 1 if n + 1 < len(marks) else len(lines)
        names = [m.group(1) for m in (DEF_RE.match(l) for l in lines[start:end]) if m]
        out.append((title, start, end, names))
    return out, len(lines)


def render():
    text = ENGINE.read_text(encoding="utf-8")
    secs, total = sections(text)
    head = text[: secs[0][1] - 1 if secs else 0].splitlines()
    preamble = sum(1 for l in head if l.strip() and not l.lstrip().startswith("#"))
    rows = ["%s\n" % HDR,
            "# Engine map — `engine/humona.py`\n",
            "%d lines, %d sections, standard library only. Everything before the first section "
            "(%d statements) is imports, paths and constants.\n" % (total, len(secs), preamble),
            "| lines | section | what it holds |", "|---|---|---|"]
    for title, start, end, names in secs:
        shown = ", ".join("`%s`" % n for n in names[:8]) + (" …" if len(names) > 8 else "")
        rows.append("| %d–%d | **%s** | %s |" % (start, end, title, shown or "—"))
    rows += ["",
             "Rules that shape this file, from `CLAUDE.md`: standard library only; a hook may "
             "never block a session, so `urllib` and `difflib` are imported lazily and git runs "
             "in its own process group with a timeout; every model-chosen path goes through "
             "`inside()` (or `readable()` when the shared vault may answer), and `/memories` "
             "paths through `mt_path()`.",
             "",
             "Regenerate with `python3 tools/engine_map.py`; `--check` fails when it is stale, "
             "which the test suite asserts."]
    return "\n".join(rows) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    want = render()
    if a.check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != want:
            print("docs/engine-map.md is out of date — run `python3 tools/engine_map.py`")
            return 1
        print("engine map is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(want, encoding="utf-8")
    print("wrote", OUT.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
